#!/usr/bin/env python3
"""Freeze the recompiler config (work/don.toml) into config/recomp.toml, or render it back.

Freeze:  freeze_recomp_config.py <work/don.toml> [--repo-config config]
  Rewrites the three absolute paths of [general] as placeholders, copies the address list the config refers to into
  config/recomp/, and refuses (exit 1) any referred file that is not a plain text list of names and addresses.
Resume owners:  freeze_recomp_config.py --resume-owners-from <dump> --generated <dir> [--repo-config config]
  Writes config/recomp/resume_owners.csv (target_address,owner_address): for every resume target the recompiler
  reports as claimed by several owners (ps2_recomp --dump-resume-owners <dump>), the owner that <dir>/register_functions.cpp
  registers it to. Run it once, on the tree whose behaviour is to be kept; the recompiler then reproduces that tree.
Render:  freeze_recomp_config.py --render <out.toml> --disc D --out O [--repo R] [--frozen config/recomp.toml]
  Writes a runnable config with the placeholders filled in.

Placeholders: {disc} the program file of the disc, {out} the folder the recompiler writes into,
{repo} the repository root.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HEADER = """# Frozen PS2Recomp configuration for Battle Stadium D.O.N (tools/pipeline/freeze_recomp_config.py).
# Only addresses, sizes, names and options. Placeholders, filled in by `freeze_recomp_config.py --render`:
#   {disc}  the program file of the disc (SLPS_256.75)
#   {out}   the folder the recompiler writes the generated sources into
#   {repo}  the root of this repository
"""
PATH_KEYS = {"input": "{disc}", "output": "{out}/"}
CSV_HEADER = "Name,Start,End,Size"
CSV_ROW = re.compile(r"^[A-Za-z0-9_.$@<>:~-]+,0x[0-9A-Fa-f]{8},0x[0-9A-Fa-f]{8},\d+$")
RESUME_OWNERS_HEADER = "target_address,owner_address"
RESUME_OWNERS_KEY = 'resume_owners = "{repo}/config/recomp/resume_owners.csv"'
REGISTER_ENTRY = re.compile(r"^\s*\{0x([0-9a-fA-F]+)u, (\w+)\},?\s*$")
OWNER_NAME = re.compile(r"_0x([0-9a-fA-F]+)$")
KEY_LINE = re.compile(r'^(\w+)\s*=\s*"([^"]*)"\s*$')


def check_text_list(path: Path) -> str | None:
    """Return a description of what is wrong, or None when the file is a Name,Start,End,Size list."""
    data = path.read_bytes()
    if b"\0" in data:
        return f"{path.name}: contains NUL bytes ({len(data)} bytes), it is binary"
    try:
        lines = data.decode("utf-8").splitlines()
    except UnicodeDecodeError as e:
        return f"{path.name}: not UTF-8 text ({e})"
    if not lines or lines[0] != CSV_HEADER:
        return f"{path.name}: first line is not '{CSV_HEADER}'"
    for n, line in enumerate(lines[1:], 2):
        if not CSV_ROW.match(line):
            return f"{path.name}: line {n} is not a name,start,end,size row ({len(line)} chars)"
    return None


def freeze(src: Path, config_dir: Path) -> int:
    lines = src.read_text(encoding="utf-8").splitlines()
    out_lines = [HEADER.rstrip("\n")]
    section = None
    for line in lines:
        if line.startswith(("# PS2Recomp configuration", "# Generated by")):
            continue
        m = re.match(r"^\[(\w+)\]\s*$", line)
        if m:
            section = m.group(1)
        k = KEY_LINE.match(line) if section == "general" else None
        if k and k.group(1) in PATH_KEYS:
            line = f'{k.group(1)} = "{PATH_KEYS[k.group(1)]}"'
        elif k and k.group(1) == "ghidra_output":
            csv = Path(k.group(2))
            if not csv.is_file():
                print(f"[freeze] missing referred file {csv}", file=sys.stderr)
                return 1
            problem = check_text_list(csv)
            if problem:
                print(f"[freeze] refusing: {problem}", file=sys.stderr)
                return 1
            dest = config_dir / "recomp" / csv.name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(csv, dest)
            line = f'ghidra_output = "{{repo}}/config/recomp/{csv.name}"\n{RESUME_OWNERS_KEY}'
        elif k and k.group(1) == "resume_owners":
            continue
        out_lines.append(line)
    text = "\n".join(out_lines) + "\n"
    if re.search(r"/media|/home|[A-Za-z]:\\", text):
        print("[freeze] refusing: an absolute path is left in the config", file=sys.stderr)
        return 1
    (config_dir / "recomp.toml").write_text(text, encoding="utf-8")
    print(f"[freeze] wrote {config_dir / 'recomp.toml'}")
    return 0


def freeze_resume_owners(dump: Path, generated: Path, config_dir: Path) -> int:
    """Write config/recomp/resume_owners.csv from the recompiler's candidate dump and a generated tree."""
    registered = {}
    for line in (generated / "register_functions.cpp").read_text(encoding="utf-8").splitlines():
        m = REGISTER_ENTRY.match(line)
        if m:
            registered[int(m.group(1), 16)] = m.group(2)
    rows = []
    for line in dump.read_text(encoding="utf-8").splitlines():
        target, *candidates = (int(field, 16) for field in line.split(","))
        name = registered.get(target)
        owner = OWNER_NAME.search(name) if name else None
        if not owner or int(owner.group(1), 16) not in candidates:
            print(f"[freeze] target 0x{target:08x}: registered owner {name!r} is not one of its candidates", file=sys.stderr)
            return 1
        rows.append((target, int(owner.group(1), 16)))
    dest = config_dir / "recomp" / "resume_owners.csv"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(
        "".join(f"{line}\n" for line in [RESUME_OWNERS_HEADER] + [f"0x{t:08x},0x{o:08x}" for t, o in sorted(rows)]),
        encoding="utf-8",
    )
    print(f"[freeze] wrote {dest} ({len(rows)} targets)")
    return 0


def render(frozen: Path, dest: Path, disc: Path, out: Path, repo: Path) -> int:
    values = {"{disc}": disc, "{out}": out, "{repo}": repo}
    lines = []
    for line in frozen.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            for key, value in values.items():
                line = line.replace(key, Path(value).resolve().as_posix())
        lines.append(line)
    text = "\n".join(lines) + "\n"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8")
    print(f"[freeze] rendered {dest}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", type=Path, help="work/don.toml to freeze")
    ap.add_argument("--config-dir", type=Path, default=REPO / "config")
    ap.add_argument("--render", type=Path, metavar="OUT_TOML")
    ap.add_argument("--disc", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--repo", type=Path, default=REPO)
    ap.add_argument("--resume-owners-from", type=Path, metavar="DUMP", help="ps2_recomp --dump-resume-owners file")
    ap.add_argument("--generated", type=Path, help="generated tree whose resume owners are kept")
    a = ap.parse_args()
    if a.resume_owners_from:
        if not a.generated:
            ap.error("--resume-owners-from needs --generated")
        return freeze_resume_owners(a.resume_owners_from, a.generated, a.config_dir)
    if a.render:
        if not (a.disc and a.out):
            ap.error("--render needs --disc and --out")
        return render(a.config_dir / "recomp.toml", a.render, a.disc, a.out, a.repo)
    if not a.source:
        ap.error("give the work/don.toml to freeze, or --render")
    return freeze(a.source, a.config_dir)


if __name__ == "__main__":
    sys.exit(main())
