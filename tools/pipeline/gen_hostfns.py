"""Writes don_host_fns.h and shim/ps2_syscalls.h, shim/ps2_stubs.h from ns_calls.txt.

ns_calls.txt: 'count ps2_syscalls::Name' / 'count ps2_stubs::Name' lines, taken from generated/*.cpp.
Origin: work/t605/abi/gen_hostfns.py (T-605 draft), moved by T-610. Writes into src/game_module/ (don_host_fns.h, shim/).
Run: uv run --no-project python -I tools/pipeline/gen_hostfns.py
"""
from pathlib import Path

here = Path(__file__).resolve().parent
out_dir = here.parent.parent / "src" / "game_module"
names = {"ps2_syscalls": [], "ps2_stubs": []}
for line in (here / "ns_calls.txt").read_text().splitlines():
    parts = line.split()
    if len(parts) != 2 or "::" not in parts[1]:
        continue
    ns, name = parts[1].split("::")
    if ns in names:
        names[ns].append(name)
for ns in names:
    names[ns] = sorted(set(names[ns]))

enum = ["// Generated by gen_hostfns.py from the host functions that generated code calls by name.",
        "// One id per ps2_syscalls::X / ps2_stubs::X call target (signature DonHostFn).",
        "#pragma once", "enum DonHostFnId : uint32_t", "{"]
for ns, short in (("ps2_syscalls", "SYS"), ("ps2_stubs", "STUB")):
    for n in names[ns]:
        enum.append(f"    DON_HF_{short}_{n},")
enum += ["    DON_HF_COUNT", "};", ""]
(out_dir / "don_host_fns.h").write_text("\n".join(enum))

shim = out_dir / "shim"
shim.mkdir(exist_ok=True)
for ns, short, guard in (("ps2_syscalls", "SYS", "PS2_SYSCALLS_H"), ("ps2_stubs", "STUB", "PS2_STUBS_H")):
    out = [f"#ifndef {guard}", f"#define {guard}", '#include "ps2_runtime.h"', "",
           f"namespace {ns}", "{"]
    for n in names[ns]:
        out.append(f"inline void {n}(uint8_t *rdram, R5900Context *ctx, PS2Runtime *runtime)"
                   f" {{ don_rt->calls->host_fn[DON_HF_{short}_{n}](rdram, ctx, runtime); }}")
    out += ["}", "", f"#endif // {guard}", ""]
    (shim / f"{ns}.h").write_text("\n".join(out))
print({k: len(v) for k, v in names.items()})

# src/host/don_runtime_bridge_fns.cpp: the host side of DonRuntimeCalls::host_fn, in DonHostFnId order. The real
# functions take (uint8_t *, R5900Context *, PS2Runtime *); the module's DonHostFn has the same signature over the
# ABI's identical R5900Context and the opaque runtime pointer, so the table holds the real functions.
host = ["// Generated by tools/pipeline/gen_hostfns.py from tools/pipeline/ns_calls.txt: do not edit.",
        "// The host functions generated code calls by name, in DonHostFnId order (src/game_module/don_host_fns.h).",
        "// The signature is the real one; the module calls it as DonHostFn (same layout of R5900Context, opaque runtime).",
        '#include "ps2_runtime.h"', '#include "ps2_stubs.h"', '#include "ps2_syscalls.h"', "",
        "#include <cstddef>", "",
        "namespace",
        "{",
        "using HostFn = void (*)(uint8_t *, R5900Context *, PS2Runtime *);",
        "",
        "#define DON_HOST_FN(ns, name) reinterpret_cast<void *>(static_cast<HostFn>(&ns::name))",
        "",
        "void *const g_hostFns[] = {"]
for ns in ("ps2_syscalls", "ps2_stubs"):
    for n in names[ns]:
        host.append(f"    DON_HOST_FN({ns}, {n}),")
host += ["};", "}", "",
         "// Copies the table into `out` (DonRuntimeCalls::host_fn) and returns its length; 0 when `capacity` is too small.",
         "size_t don_bridge_fill_host_fns(void **out, size_t capacity)",
         "{",
         "    constexpr size_t count = sizeof(g_hostFns) / sizeof(g_hostFns[0]);",
         "    if (capacity < count)",
         "        return 0;",
         "    for (size_t i = 0; i < count; ++i)",
         "        out[i] = g_hostFns[i];",
         "    return count;",
         "}", ""]
(here.parent.parent / "src" / "host" / "don_runtime_bridge_fns.cpp").write_text("\n".join(host))
