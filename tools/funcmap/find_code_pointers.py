#!/usr/bin/env python3
"""Find every address of the main text that the game can hold as a code pointer and classify it.

Usage:
  find_code_pointers.py --csv config/functions.ghidra.csv --layout config/layout.toml \
      --elf disc/SLPS_256.75 --vu docs/knowledge/data/vu_programs.tsv

The recompiled game can only jump through a register to a row of the function map or to an entry
point of the recompiler configuration. Candidates (multiples of 4 inside [text.start, text.end))
come from three sources:
  data       4-aligned words of the load segment after the text (VU microprograms and
             kernel_patch_blob islands skipped)
  code_pair  lui rt + addiu/ori rt, rt within the next LOOKAHEAD instructions, inside rows
  jal        targets of jal instructions that lie inside rows
Each distinct candidate is row_start, inside_row, new_code (decodes as R5900 up to a jr $ra) or
rejected. inside_row and new_code go to config/extra_entry_points.txt, rejected to
config/code_pointers_reject.txt; addresses already listed in the reject file (manual additions)
are kept there and never written to the entry points file. Needs rabbitizer.
"""
import argparse
import json
import struct
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import layout  # noqa: E402

SOURCES = ('data', 'code_pair', 'jal')
CLASSES = ('row_start', 'inside_row', 'new_code', 'rejected')
MAX_DECODE = 4096  # instructions to look at for a jr $ra
JR_RA = 0x03E00008
OP_JAL = 0x03
NEW_CODE_LIMIT = 500

EXTRA_HEADER = [
    '# Extra entry points for the recompiler: code pointers that are not the start of a row of',
    '# config/functions.ghidra.csv (inside_row) or that are in no row but decode as code (new_code).',
    '# Generated by tools/funcmap/find_code_pointers.py; do not edit by hand.',
    '# To exclude an address add it to config/code_pointers_reject.txt (manual additions are respected).',
]
REJECT_HEADER = [
    '# Code pointer candidates that are not code: they decode as invalid R5900 or have no jr $ra nearby.',
    '# Generated by tools/funcmap/find_code_pointers.py. Manual additions are respected: an address listed',
    '# here is never written to config/extra_entry_points.txt and is kept when the file is regenerated.',
]


def read_layout(path):
    """Return (text_start, text_end, [(start, end)] of the kernel_patch_blob islands)."""
    d = tomllib.loads(Path(path).read_text())
    blobs = [(i['start'], i['end']) for i in d.get('island', []) if i['kind'] == 'kernel_patch_blob']
    return d['text']['start'], d['text']['end'], blobs


def text_rows(rows, text_start, text_end):
    return [r for r in rows if text_start <= r[1] < text_end]


def build_coverage(rows, text_start, text_end):
    """Return (set of row starts, bytearray with one flag per text word that lies inside a row)."""
    n = (text_end - text_start) // 4
    covered = bytearray(n)
    starts = set()
    for _, s, e in rows:
        starts.add(s)
        a = (s - text_start) // 4
        b = min(n, (e - text_start + 3) // 4)
        if b > a:
            covered[a:b] = b'\x01' * (b - a)
    return starts, covered


def is_candidate(v, text_start, text_end):
    return text_start <= v < text_end and v % 4 == 0


def add(cands, addr, source, found_at):
    cands.setdefault(addr, {}).setdefault(source, found_at)


def allowed_ranges(lo, hi, excluded):
    """[lo, hi) minus the excluded ranges, as a sorted list of (start, end)."""
    out = []
    cur = lo
    for s, e in sorted(excluded):
        if e <= cur or s >= hi:
            continue
        if s > cur:
            out.append((cur, s))
        cur = max(cur, e)
    if cur < hi:
        out.append((cur, hi))
    return out


def collect_data(blob, base, text_start, text_end, vu, blobs, cands):
    file_end = base + len(blob) // 4 * 4
    for lo, hi in allowed_ranges(text_end & ~3, file_end, list(vu) + list(blobs)):
        lo = (lo + 3) & ~3
        n = (hi - lo) // 4
        if n <= 0:
            continue
        words = struct.unpack_from(f'<{n}I', blob, lo - base)
        for i, w in enumerate(words):
            if text_start <= w < text_end and not w & 3:
                add(cands, w, 'data', lo + i * 4)


def collect_code(blob, base, text_start, text_end, covered, cands):
    n = (text_end - text_start) // 4
    first = (text_start - base) // 4
    words = struct.unpack_from(f'<{first + n}I', blob)

    def inside(i):
        return 0 <= i - first < n and covered[i - first]

    for i in range(first, first + n):
        if not covered[i - first]:
            continue
        w = words[i]
        op = w >> 26
        pc = base + i * 4
        if op == OP_JAL:
            t = ((w & 0x3FFFFFF) << 2) | (pc & 0xF0000000)
            if is_candidate(t, text_start, text_end):
                add(cands, t, 'jal', pc)
        elif op == layout.OP_LUI:
            rt = (w >> 16) & 0x1F
            hi = w & 0xFFFF
            for j in range(i + 1, i + 1 + layout.LOOKAHEAD):
                if j >= first + n:
                    break
                x = words[j]
                xop = x >> 26
                if xop not in (layout.OP_ADDIU, layout.OP_ORI) or (x >> 21) & 0x1F != rt or (x >> 16) & 0x1F != rt:
                    continue
                lo = x & 0xFFFF
                if xop == layout.OP_ADDIU and lo & 0x8000:
                    lo -= 0x10000
                addr = ((hi << 16) + lo) & 0xFFFFFFFF
                if inside(j) and is_candidate(addr, text_start, text_end):
                    add(cands, addr, 'code_pair', pc)
                break


def decode_run(blob, base, addr):
    """Decode from addr until a jr $ra. Return (ok, instructions decoded, reason)."""
    for k in range(MAX_DECODE):
        a = addr + k * 4
        off = a - base
        if off < 0 or off + 4 > len(blob):
            return False, k, f'runs out of the file data at 0x{a:08X}'
        w, = struct.unpack_from('<I', blob, off)
        if not layout.decode_valid(w, a):
            return False, k + 1, f'invalid word 0x{w:08X} at 0x{a:08X}'
        if w == JR_RA:
            return True, k + 1, ''
    return False, MAX_DECODE, f'no jr $ra within {MAX_DECODE} instructions'


def innermost(rows, addr):
    """Name of the smallest non-label row that contains addr (a label if there is none), or '-'."""
    best = {}
    for name, s, e in rows:
        if s > addr:
            break
        if s <= addr < e:
            k = 1 if layout.is_label(name) else 0
            if k not in best or e - s < best[k][1]:
                best[k] = (name, e - s)
    for k in (0, 1):
        if k in best:
            return best[k][0]
    return '-'


def classify_all(cands, rows, blob, base, text_start, text_end):
    """Return {class: [entry]} with each entry sorted by address."""
    starts, covered = build_coverage(rows, text_start, text_end)
    out = {c: [] for c in CLASSES}
    for addr in sorted(cands):
        found = cands[addr]
        e = {'address': addr, 'sources': [s for s in SOURCES if s in found],
             'found_at': {s: found[s] for s in SOURCES if s in found}}
        if addr in starts:
            cls = 'row_start'
        elif covered[(addr - text_start) // 4]:
            cls = 'inside_row'
            e['row'] = innermost(rows, addr)
        else:
            ok, n, why = decode_run(blob, base, addr)
            e['decoded'] = n
            if ok:
                cls = 'new_code'
            else:
                cls = 'rejected'
                e['reason'] = why
        out[cls].append(e)
    return out


def count(classes):
    counts = {c: len(classes[c]) for c in CLASSES}
    by_source = {s: {c: sum(1 for e in classes[c] if s in e['sources']) for c in CLASSES} for s in SOURCES}
    return counts, by_source


def parse_addr_file(path):
    """Return {address: comment} of a file of '0x........ # comment' lines (missing file: empty)."""
    p = Path(path)
    out = {}
    if not p.exists():
        return out
    for line in p.read_text().splitlines():
        code, _, comment = line.partition('#')
        code = code.strip()
        if code:
            out[int(code, 16)] = comment.strip()
    return out


def render_lines(header, items):
    return '\n'.join(header + [f'0x{a:08X}  # {c}' for a, c in sorted(items)]) + '\n'


def extra_comment(e):
    if 'row' in e:
        return f"inside_row {e['row']} {','.join(e['sources'])}"
    return f"new_code {','.join(e['sources'])}"


def build_outputs(classes, manual_reject):
    """Return (extra file text, reject file text, number of candidates held back by the reject file)."""
    extra = {}
    held = 0
    for c in ('inside_row', 'new_code'):
        for e in classes[c]:
            if e['address'] in manual_reject:
                held += 1
            else:
                extra[e['address']] = extra_comment(e)
    reject = dict(manual_reject)
    for e in classes['rejected']:
        reject[e['address']] = f"rejected {','.join(e['sources'])}: {e['reason']}"
    return render_lines(EXTRA_HEADER, extra.items()), render_lines(REJECT_HEADER, reject.items()), held


def run(rows, blob, base, text_start, text_end, vu, blobs):
    rows = text_rows(rows, text_start, text_end)
    cands = {}
    _, covered = build_coverage(rows, text_start, text_end)
    collect_data(blob, base, text_start, text_end, vu, blobs, cands)
    collect_code(blob, base, text_start, text_end, covered, cands)
    return classify_all(cands, rows, blob, base, text_start, text_end), rows


def main(argv):
    ap = argparse.ArgumentParser(description='Classify the code pointers of the PS2 executable.')
    ap.add_argument('--csv', required=True)
    ap.add_argument('--layout', required=True)
    ap.add_argument('--elf', required=True)
    ap.add_argument('--vu', required=True)
    ap.add_argument('--extra', default='config/extra_entry_points.txt')
    ap.add_argument('--reject', default='config/code_pointers_reject.txt')
    ap.add_argument('--report', default='work/reports/code_pointers.json')
    args = ap.parse_args(argv)

    text_start, text_end, blobs = read_layout(args.layout)
    _, base, blob, _, _ = layout.load(args.elf)
    vu = layout.read_vu(args.vu)
    classes, rows = run(layout.read_rows(args.csv), blob, base, text_start, text_end, vu, blobs)
    counts, by_source = count(classes)
    print(f'rows in the text: {len(rows)}')
    print(f'counts: {counts}')
    for s in SOURCES:
        print(f'  {s}: {by_source[s]}')
    if counts['new_code'] > NEW_CODE_LIMIT:
        print(f"new_code is {counts['new_code']} (> {NEW_CODE_LIMIT}): the Ghidra analysis looks incomplete; "
              'repeat T-006 with other options. Nothing written.', file=sys.stderr)
        return 1

    manual = parse_addr_file(args.reject)
    extra_txt, reject_txt, held = build_outputs(classes, manual)
    Path(args.extra).write_text(extra_txt)
    Path(args.reject).write_text(reject_txt)
    report = {'counts': counts, 'counts_by_source': by_source, 'held_back_by_reject_file': held,
              'inside_row': classes['inside_row'], 'new_code': classes['new_code'],
              'rejected': classes['rejected']}
    Path(args.report).parent.mkdir(parents=True, exist_ok=True)
    Path(args.report).write_text(json.dumps(report, indent=1) + '\n')
    print(f'held back by the reject file: {held}')
    print(f'wrote {args.extra}, {args.reject}, {args.report}')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
