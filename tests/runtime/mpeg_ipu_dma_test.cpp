// T-305 patch 0064: the movie stream the game sends to the decoder over DMA channel 4 reaches the MPEG stub.
//
// Battle Stadium D.O.N does not hand its movie to sceMpegAddBs: Sofdec writes the stream to the IPU through DMA
// channel 4 in source-chain mode. The stub takes the bytes from the started channel when sceMpegGetPicture
// runs. This test builds a chain like the game's (one "end" tag followed by its payload), starts channel 4 and
// asks for pictures:
//
//   * the stream is a synthetic MPEG-2 video of SMPTE colour bars (64x32, four pictures, the first one checked, written by FFmpeg's
//     mpeg2video encoder from a generated test source; nothing from the game), followed by a sequence end code;
//   * every picture arrives, with the size the stream has, in the strip layout the game expects (one strip per
//     16-pixel column, 16 pixels per row), and the bars have their colours at known places;
//   * when the chain is consumed channel 4 completes: STR is cleared and D_STAT bit 4 is set.
//
// Without patch 0064 channel 4 is never read, no picture is ever decoded and the checks on the colours fail.
// Needs the runtime built with FFmpeg (PS2X_ENABLE_FFMPEG=ON). Run it with DISPLAY unset (the test unsets it).

